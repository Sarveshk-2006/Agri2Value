class GeminiAIAdvisorProvider(BaseAIAdvisorProvider):
    """
    Gemini API Provider.
    Queries Google Gemini when GEMINI_API_KEY is available; falls back to Deterministic rules otherwise.
    """

    def __init__(self, api_key: str, model_name: str = "gemini-1.5-flash"):
        self.api_key = api_key
        self.model_name = model_name
        self.fallback = DeterministicAgronomicRuleProvider()

    async def generate_advice(
        self,
        query: str,
        farmer_name: str,
        language: str,
        farm_context: Optional[Dict[str, Any]] = None,
        crop_context: Optional[Dict[str, Any]] = None,
    ) -> AIAdvisorResponse:
        if not self.api_key:
            return await self.fallback.generate_advice(query, farmer_name, language, farm_context, crop_context)

        system_instruction = (
            "You are Agri2Value (कृषि-मूल्य) AI Post-Harvest Advisor. "
            "Provide concise, highly accurate, deterministic-grounded post-harvest, market, and agronomy advice for Indian farmers. "
            "Never hallucinate prices or invent fake buyer guarantees. "
            f"Address the farmer respectfully as {farmer_name}. "
            f"Respond in {language} language if appropriate or clear English with localized Indian agricultural terms. "
            f"Farm Context: {farm_context}. Crop Context: {crop_context}."
        )

        url = f"https://generativelanguage.googleapis.com/v1beta/models/{self.model_name}:generateContent?key={self.api_key}"
        payload = {
            "contents": [
                {
                    "parts": [
                        {"text": f"System: {system_instruction}\nFarmer Query: {query}"}
                    ]
                }
            ],
            "generationConfig": {
                "temperature": 0.2,
                "maxOutputTokens": 400,
            },
        }

        try:
            async with httpx.AsyncClient(timeout=10.0) as client:
                resp = await client.post(url, json=payload)
                if resp.status_code == 200:
                    data = resp.json()
                    candidates = data.get("candidates", [])
                    if candidates:
                        text = candidates[0].get("content", {}).get("parts", [{}])[0].get("text", "")
                        if text:
                            return AIAdvisorResponse(
                                answer=text.strip(),
                                provider="google_gemini",
                                is_ai_generated=True,
                                model_name=self.model_name,
                                confidence_score=0.92,
                                suggested_actions=[
                                    {"label": "Evaluate Profit Engine", "route": "/app/decision"},
                                    {"label": "Check Mandi Benchmark", "route": "/app/market"},
                                ],
                                disclaimer="AI-generated post-harvest advisory. Inspect crop lots physically before commercial execution.",
                            )
                logger.warn("Gemini API call returned non-200, falling back to deterministic engine", status=resp.status_code)
        except Exception as e:
            logger.warn("Gemini API exception, falling back to deterministic engine", error=str(e))

        return await self.fallback.generate_advice(query, farmer_name, language, farm_context, crop_context)


class AIAdvisorManager:
    """Singleton Manager resolving the configured provider."""

    def __init__(self):
        gemini_key = settings.GEMINI_API_KEY.strip()
        provider_mode = settings.AI_ADVISOR_PROVIDER.lower().strip()

        if provider_mode == "gemini" or (provider_mode == "auto" and gemini_key):
            self.provider: BaseAIAdvisorProvider = GeminiAIAdvisorProvider(
                api_key=gemini_key,
                model_name=settings.AI_ADVISOR_MODEL or "gemini-1.5-flash",
            )
            logger.info("AIAdvisorManager initialized with Gemini Provider")
        else:
            self.provider = DeterministicAgronomicRuleProvider()
            logger.info("AIAdvisorManager initialized with Deterministic Agronomic Rules Engine")

    async def get_advice(
        self,
        query: str,
        farmer_name: str,
        language: str = "en",
        farm_context: Optional[Dict[str, Any]] = None,
        crop_context: Optional[Dict[str, Any]] = None,
    ) -> AIAdvisorResponse:
        return await self.provider.generate_advice(query, farmer_name, language, farm_context, crop_context)


ai_advisor_service = AIAdvisorManager()

